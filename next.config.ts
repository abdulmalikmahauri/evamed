import type { NextConfig } from 'next';

/**
 * Две конфигурации сборки.
 *
 * Обычная — для развёртывания на собственном сервере: работают заголовки
 * безопасности из proxy.ts и серверный рендеринг.
 *
 * Статическая (EVAMED_STATIC=true) — для показа на GitHub Pages, где сервера
 * нет вовсе. Формы при этом работают: проверка полей и подтверждение целиком
 * выполняются в браузере, а приёмник заявок не настроен, поэтому данные
 * никуда не уходят — то же поведение, что и на сервере в режиме показа.
 *
 * Заголовки безопасности при статической выгрузке не применяются: их
 * выставляет сервер, а Pages отдаёт файлы. Для демонстрации это допустимо,
 * для продакшна — нет, поэтому продакшн собирается обычным способом.
 */
const isStatic = process.env.EVAMED_STATIC === 'true';

/**
 * Pages отдаёт сайт из подпути вида /имя-репозитория, поэтому ссылки и пути
 * к файлам должны учитывать префикс. Вынесен в переменную, чтобы при переезде
 * на собственный домен ничего не переписывать.
 */
const basePath = isStatic ? (process.env.EVAMED_BASE_PATH ?? '/evamed') : '';

const nextConfig: NextConfig = {
  ...(isStatic
    ? {
        output: 'export' as const,
        basePath,
        // Pages не умеет оптимизировать изображения на лету
        images: { unoptimized: true },
        // адрес вида /tseny/ отдаётся как /tseny/index.html
        trailingSlash: true,
      }
    : {}),
};

export default nextConfig;
