/**
 * Данные правового раздела.
 *
 * Раздел обязателен: приказ Минздрава России от 04.03.2022 № 118н устанавливает
 * перечень сведений, которые медицинская организация размещает на своём сайте.
 *
 * Реквизиты клиника ещё не передала. Каждое неизвестное значение равно null
 * и печатается как «Уточняется». Правдоподобная заглушка здесь опаснее пустого
 * места: опубликованный номер лицензии или ИНН клиника примет за настоящий,
 * а пациент — за проверяемый факт. Когда документы поступят, правится только
 * этот файл, разметка страниц не меняется.
 */

/** Значение реквизита: строка, если данные переданы, иначе null. */
export type LegalValue = string | null;

/** Печатается вместо непереданного реквизита. */
export const NOT_PROVIDED = 'Уточняется';

/** Данные переданы и пригодны к публикации. */
export function isProvided(value: LegalValue): value is string {
  return typeof value === 'string' && value.trim().length > 0;
}

/** Значение для вывода: либо реквизит, либо явная отметка о его отсутствии. */
export function legalValue(value: LegalValue): string {
  return isProvided(value) ? value : NOT_PROVIDED;
}

/** Строка реквизита. */
export interface LegalField {
  label: string;
  value: LegalValue;
  /** пояснение под строкой: откуда берётся значение или что именно ожидается */
  note?: string;
}

/** Раздел сведений о медорганизации. */
export interface LegalSection {
  /** якорь для оглавления страницы */
  id: string;
  title: string;
  /** абзацы перед перечнем реквизитов */
  intro?: readonly string[];
  fields: readonly LegalField[];
}

