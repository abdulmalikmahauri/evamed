/**
 * Карточка врача для блока на главной и для будущего каталога.
 *
 * Персональная страница есть не у каждого: её нельзя собрать, пока клиника
 * не передала образование, категории и реквизиты аккредитации. Придумывать
 * эти сведения нельзя — это данные о квалификации медицинского работника.
 * Поэтому у карточки без страницы просто нет ссылки «Подробнее», а не ссылка
 * в никуда.
 */
export interface DoctorCard {
  slug: string;
  monogram: string;
  name: string;
  spec: string;
  meta: string;
  price: number;
  /** есть ли персональная страница по адресу /vrachi/{slug} */
  hasProfile: boolean;
}

