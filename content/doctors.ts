/**
 * Карточки врачей.
 *
 * Данные отделены от разметки: состав услуг, цены и график правит
 * администратор клиники. Формулировки не содержат обещаний результата —
 * ограничение рекламы медицинских услуг.
 *
 * Сведения об образовании и аккредитации публикуются только после сверки
 * с документами специалиста: до сверки карточка остаётся черновой.
 */

/**
 * Позиция прайса врача. slug ведёт на карточку услуги и указывается только
 * тогда, когда карточка описывает ровно эту позицию по этой же цене.
 * Повторный приём стоит иначе и отдельной страницы не имеет — ссылки у него
 * нет, иначе посетитель уходил бы со страницы «2 800 ₽» на страницу «3 500 ₽».
 */
export interface DoctorService {
  slug?: string;
  name: string;
  price: number;
}

export interface Doctor {
  slug: string;
  fullName: string;
  /** сокращённая форма для описания страницы: «Ахмадова М. Р.» */
  shortName: string;
  /** монограмма вместо фотографии, пока фотосъёмка не проведена */
  monogram: string;
  /** надзаголовок над именем */
  specialty: string;
  /** специальность в сводке параметров, именительный падеж */
  specialtyField: string;
  lead: string;
  /** год начала работы по специальности */
  sinceYear: number;
  degree: string;
  /** график в сводке параметров */
  schedule: string;
  /** график в описании страницы: «по будням 9:00–15:00» */
  scheduleShort: string;
  /** цена первичного приёма */
  price: number;
  education: readonly string[];
  /** блок «Приём» */
  receptionNote: string;
  services: readonly DoctorService[];
  /** блок «О враче», по абзацам */
  about: readonly string[];
  /** участие в программе наблюдения */
  programRole: string;
  /** строка под ценой в карточке записи */
  bookingMeta: string;
  /** пояснение под разделителем в карточке записи */
  bookingNote: string;
  /** направления в боковой карточке */
  directions: readonly string[];
}

