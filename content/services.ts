/**
 * Каталог услуг.
 *
 * Данные отделены от разметки: цены, состав и формулировки правит
 * администратор клиники, не трогая компоненты. Тексты проходят проверку
 * на ограничения рекламы медуслуг — без гарантий результата и превосходных
 * степеней, с обязательным указанием на консультацию специалиста.
 */

const NBSP = '\u00A0';

/**
 * «3 200 ₽» неразрывными пробелами. Форматирование ручное, а не через
 * toLocaleString: разная локальная база у сервера и клиента даёт расхождение
 * разметки при гидратации.
 */
export function formatPrice(value: number): string {
  const grouped = String(Math.round(value)).replace(/\B(?=(\d{3})+(?!\d))/g, NBSP);
  return `${grouped}${NBSP}₽`;
}

