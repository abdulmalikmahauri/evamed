export interface CrumbLink {
  label: string;
  href: string;
}

export interface RelatedService {
  slug: string;
  name: string;
  price: number;
}

export interface Service {
  slug: string;
  /** витринное название: h1 и заголовок вкладки */
  name: string;
  /** направление, надзаголовок над h1 */
  direction: string;
  /** промежуточные звенья хлебных крошек между «Главной» и страницей */
  breadcrumbs: readonly CrumbLink[];
  /** последнее звено хлебных крошек */
  crumb: string;
  lead: string;
  price: number;
  duration: string;
  /** где проводится */
  place: string;
  /** когда готов результат */
  result: string;
  /** подготовка одной строкой, для сводки параметров */
  preparationShort: string;
  /** когда назначают */
  indications: string;
  /** ход исследования */
  procedure: readonly string[];
  /** подготовка развёрнуто */
  preparation: string;
  /** что после */
  afterwards: string;
  /** противопоказания и ограничения */
  contraindications: string;
  /** строка под ценой в карточке записи */
  bookingNote: string;
  /** участие услуги в программе наблюдения */
  programNote: string;
  related: readonly RelatedService[];
}

